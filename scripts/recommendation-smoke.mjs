import assert from 'node:assert/strict'
const base = process.env.SITE_BASE_URL || 'http://localhost:3001'
assert.ok(['localhost', '127.0.0.1'].includes(new URL(base).hostname), 'Use an isolated local server')
const page = await fetch(`${base}/pedido-recomendacao`, { signal: AbortSignal.timeout(45000) })
assert.equal(page.status, 200)
const html = await page.text()
assert.ok(html.includes('Falar no WhatsApp'))
assert.ok(html.includes('https://wa.me/351910419820'))
assert.ok(!html.includes('name="healthConsent"')); assert.ok(!html.includes('name="files"'))
assert.ok(!html.includes('https://apps.abacus.ai/chatllm/appllm-lib.js'))
const contact = await fetch(`${base}/contactos`, { signal: AbortSignal.timeout(45000) })
assert.equal(contact.status, 200)
assert.ok(!(await contact.text()).includes('Envie-nos uma mensagem'))
assert.equal((await fetch(`${base}/api/admin/attachments?id=test`)).status, 410)
const invalid = new FormData()
invalid.set('name', 'Test')
assert.equal((await fetch(`${base}/api/recomendacao`, { method: 'POST', headers: { origin: base }, body: invalid })).status, 410)
assert.equal((await fetch(`${base}/api/recomendacao`, { method: 'POST', headers: { origin: 'https://evil.example' }, body: invalid })).status, 410)
console.log('Advice smoke checks passed: WhatsApp link, no collection fields, no third-party chat and old endpoint disabled. No database writes or emails sent.')
